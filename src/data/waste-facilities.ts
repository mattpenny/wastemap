/** Look up a single facility by id (case-insensitive). */
export function findFacilityById(id: string): FacilityProperties | undefined {
  const needle = id.trim().toLowerCase();
  return WASTE_FACILITIES_DATA.find((f) => f.id.toLowerCase() === needle);
}

