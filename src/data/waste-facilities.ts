/**
 * Hong Kong Waste Management Facilities — official EPD data
 * =========================================================================
 *
 * SOURCE OF TRUTH for the `/api/waste-data` proxy.
 *
 * Everything in this file is either taken verbatim from, or explicitly derived
 * from, the official EPD "Waste Management Facilities" (廢物處理設施) dataset:
 *
 *   dataset  epd_rcd_1629267205235_29088   (via the CSDI portal)
 *   layer    EPDWMF
 *   updated  2026-02-13
 *
 * ---------------------------------------------------------------------------
 * WHAT IS OFFICIAL vs DERIVED
 * ---------------------------------------------------------------------------
 * OFFICIAL — taken verbatim:
 *   coordinates, names (EN + TC), addresses, type, opening hours,
 *   throughputTonnesPerDay, designCapacityTonnesPerDay, voidCapacityMillionM3,
 *   and the per-facility `detail[]` rows transcribed from EPD's individual
 *   facility pages (linked in OFFICIAL_DATA_SOURCES.facilityPages).
 *
 * DERIVED — only the OITF group's combined figure:
 *   EPD's OITF page publishes about 90 tonnes/day for all seven sites combined.
 *   The per-site dataset has "N.A." for each station, so no per-site amount is
 *   invented. The combined total appears only on the collapsed OITF group row.
 *   It is marked as a group/system total, not an individual facility measure.
 *
 * ---------------------------------------------------------------------------
 * WHAT THIS DATASET DELIBERATELY DOES NOT CONTAIN
 * ---------------------------------------------------------------------------
 * There is no per-facility historical series, because EPD publishes none. The
 * facility dataset is a single current snapshot per site. The earlier revision
 * of this file carried a synthetic multi-year series generated by a formula; it
 * has been removed rather than dressed up as data. Territory-wide annual trends
 * are real and live in `hk-waste-trend.ts` instead.
 *
 * Note also that landfill "capacity" in the official data is remaining VOID
 * VOLUME in Mm³ (WENT 61, NENT 35, SENT 43) — a completely different quantity
 * from a daily tonnage, and not comparable with it.
 */

export type FacilityCategory = "Landfill" | "RTS" | "I-PARK" | "O-PARK" | "Y-PARK";

/**
 * HOW A FACILITY'S THROUGHPUT FIGURE WAS OBTAINED.
 */
export type ThroughputBasis =
  /** Published in the EPD dataset, with note/year retained verbatim. */
  | "official"
  /** EPD publishes no per-facility rate for this site. */
  | "not-published";

/** Label keys for official detail rows; translated in `src/lib/i18n.ts`. */
export type DetailLabelKey =
  | "contractor"
  | "capitalCost"
  | "wasteDeliveredTo"
  | "wasteTypes"
  | "area"
  | "aftercare"
  | "majorPlant"
  | "otherFacilities";

/**
 * One bilingual row of official detail, transcribed from EPD's individual
 * facility page (e.g. `.../prob_solutions/msw_iets.html`). Shown behind the
 * detail drawer's "Detail" toggle so the default card stays uncluttered.
 */
export interface OfficialDetailRow {
  label: DetailLabelKey;
  valueEn: string;
  valueZh: string;
}

export interface FacilityProperties {
  id: string;
  nameEn: string;
  nameZh: string;
  /**
   * Short label for the facility cards. The official code where the site has
   * one (WKTS, WENT…), otherwise the distinguishing part of the name with the
   * generic "Transfer Facility" suffix dropped. The full name replaces it on
   * hover.
   */
  shortEn: string;
  shortZh: string;
  category: FacilityCategory;
  /** [longitude, latitude] — WGS84, official. */
  coordinates: [number, number];

  /** Official throughput, tonnes/day. `null` when EPD publishes none. */
  throughputTonnesPerDay: number | null;
  /** Provenance of the throughput figure above. */
  throughputBasis: ThroughputBasis;
  /**
   * The source text for the throughput figure, verbatim, so the number can
   * always be traced back — several are qualified by a year, or describe a
   * handling capacity rather than a measured throughput.
   */
  throughputNoteEn: string | null;
  throughputNoteZh: string | null;

  /** Official designed treatment capacity, tpd. Published for very few sites. */
  designCapacityTonnesPerDay: number | null;
  /** Official remaining void capacity, Mm³. Landfills only. */
  voidCapacityMillionM3: number | null;

  addressEn: string;
  addressZh: string;
  operatorEn: string;
  operatorZh: string;
  commissionedYear: number;
  /** Month + year where EPD's facility page gives one; falls back to the year. */
  commissionedDateEn?: string;
  commissionedDateZh?: string;
  openingHoursEn: string | null;
  openingHoursZh: string | null;

  /** EPD facility-page detail rows, shown behind the drawer's Detail toggle. */
  detail?: OfficialDetailRow[];
  /** Link to the EPD facility page the detail rows were transcribed from. */
  detailSourceUrl?: string;

  /** Descriptive context. Prose only — contains no figures. */
  noteEn: string;
  noteZh: string;

  groupCode?: "OITF";
  groupEn?: string;
  groupZh?: string;
  /** Published combined system total; present on group members for group row only. */
  groupThroughputTonnesPerDay?: number;
  groupThroughputNoteEn?: string;
  groupThroughputNoteZh?: string;
}

